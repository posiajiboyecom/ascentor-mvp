// scripts/generate-api-docs.ts
// Generates docs/api-contracts.md from the strict request schemas in
// lib/validation/registry.ts, so the written contract can never drift from the
// code that enforces it.
//   npm run docs:api
import fs from 'node:fs';
import path from 'node:path';
import { z } from 'zod';
import { BODY_SCHEMAS } from '../lib/validation/registry';

type Json = { type?: string | string[]; properties?: Record<string, Json>; required?: string[]; enum?: unknown[]; anyOf?: Json[]; oneOf?: Json[]; items?: Json; const?: unknown; format?: string; minLength?: number; maxLength?: number; minimum?: number; maximum?: number; pattern?: string };

function typeOf(s: Json): string {
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((e) => JSON.stringify(e)).join(' | ');
  if (s.anyOf) return [...new Set(s.anyOf.map(typeOf))].join(' | ');
  if (s.oneOf) return [...new Set(s.oneOf.map(typeOf))].join(' | ');
  if (s.type === 'array') return `${s.items ? typeOf(s.items) : 'any'}[]`;
  const t = Array.isArray(s.type) ? s.type.join(' | ') : s.type ?? 'any';
  const bits: string[] = [];
  if (s.format) bits.push(s.format);
  if (s.minLength !== undefined || s.maxLength !== undefined) bits.push(`${s.minLength ?? 0}..${s.maxLength ?? ''} chars`);
  if (s.minimum !== undefined || s.maximum !== undefined) bits.push(`${s.minimum ?? ''}..${s.maximum ?? ''}`);
  return bits.length ? `${t} (${bits.join(', ')})` : t;
}

function rows(schema: Json): { field: string; type: string; required: boolean }[] {
  const out: { field: string; type: string; required: boolean }[] = [];
  const variants = schema.anyOf ?? schema.oneOf;
  if (variants) {
    variants.forEach((v, i) => rows(v).forEach((r) => out.push({ ...r, field: `${r.field}`, type: `${r.type}${variants.length > 1 ? ` (variant ${i + 1})` : ''}` })));
    return out;
  }
  const req = new Set(schema.required ?? []);
  for (const [k, v] of Object.entries(schema.properties ?? {})) out.push({ field: k, type: typeOf(v), required: req.has(k) });
  return out;
}

const lines: string[] = [
  '# API request contracts',
  '',
  'Generated by `npm run docs:api` from `lib/validation/registry.ts`. Do not edit by hand.',
  '',
  'Every JSON body is validated by a **strict** Zod schema: unknown fields are rejected with HTTP 400 and a',
  'field-level `issues` array. Routes that share a path across HTTP methods list each variant.',
  '',
];

const groups = new Map<string, string[]>();
for (const key of Object.keys(BODY_SCHEMAS).sort()) {
  const route = key.split('#')[0];
  const group = route.split('/')[2] ?? 'other';
  groups.set(group, [...(groups.get(group) ?? []), key]);
}

for (const [group, keys] of groups) {
  lines.push(`## ${group}`, '');
  for (const key of keys) {
    const [route, label] = key.split('#');
    const json = z.toJSONSchema(BODY_SCHEMAS[key], { unrepresentable: 'any', io: 'input' }) as Json;
    lines.push(`### \`${route}\`${label ? ` (${label})` : ''}`, '');
    const r = rows(json);
    if (!r.length) { lines.push('Empty body.', ''); continue; }
    lines.push('| Field | Type | Required |', '|-------|------|----------|');
    r.forEach((x) => lines.push(`| \`${x.field}\` | ${x.type.replace(/\|/g, '\\|')} | ${x.required ? 'yes' : 'no'} |`));
    lines.push('');
  }
}

const out = path.resolve(__dirname, '../docs/api-contracts.md');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), out)} (${Object.keys(BODY_SCHEMAS).length} contracts)`);
