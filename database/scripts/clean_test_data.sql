-- ============================================================================
-- clean_test_data.sql  -  wipe ALL test payment data, keep only real customers
--
-- Run in the Supabase SQL editor, in TWO steps. It refuses to delete anything
-- until you list the REAL paid customers, so a real payment cannot be lost.
--
-- What it does NOT touch: registrants who have not paid (they may be real leads
-- to call), user accounts, or anything outside payments/Summit/notifications.
-- ============================================================================


-- ── STEP 1: run this alone. Every "paid" Summit row the dashboard counts. ────
-- Compare with the Paystack dashboard. The real ones have a Paystack
-- transaction id. Write down the emails of the REAL paid customers.
select full_name, email, whatsapp, attendance_type,
       amount_paid, paid_at, payment_provider_tx_id, payment_reference
from public.summit_registrations
where payment_status = 'paid'
order by paid_at desc;

-- How many rows exist in each table (for reference):
select
  (select count(*) from public.summit_registrations)                       as registrations,
  (select count(*) from public.summit_registrations where payment_status='paid') as paid_registrations,
  (select count(*) from public.payment_attempts)                           as attempts,
  (select count(*) from public.payments)                                   as subscription_payment_rows;


-- ── STEP 2: fill in keep_emails, then run this whole block ──────────────────
-- Real paid customers only (the 3 people who actually paid, 11k total).
do $$
declare
  keep_emails text[] := array[
    -- 'real.customer1@gmail.com',
    -- 'real.customer2@gmail.com',
    -- 'real.customer3@gmail.com'
  ]::text[];

  -- Unpaid TEST registrations to remove (the team's own emails). Anything else
  -- unpaid is kept, because it may be a real person to follow up.
  test_emails text[] := array[
    -- 'yourteam@ascentorbi.com'
  ]::text[];
  test_patterns text[] := array['%test%', '%@example.%'];

  -- Free mode is on and there are 0 paying subscribers, so every row in
  -- public.payments is test data. Set to false if a real subscriber ever paid.
  delete_all_subscription_payments boolean := true;

  n_paid_regs int; n_unpaid_regs int; n_attempts int; n_payments int := 0; n_notifs int; n_reset int;
begin
  if coalesce(array_length(keep_emails, 1), 0) = 0 then
    raise exception 'STOP: fill keep_emails with the real paid customers from STEP 1 first. Nothing was deleted.';
  end if;

  keep_emails := (select array_agg(lower(trim(e))) from unnest(keep_emails) e);
  test_emails := coalesce((select array_agg(lower(trim(e))) from unnest(test_emails) e), array[]::text[]);

  -- 1. Every checkout attempt except those belonging to the kept customers.
  delete from public.payment_attempts
  where registration_id is null
     or registration_id not in (
          select id from public.summit_registrations where lower(email) = any(keep_emails)
        );
  get diagnostics n_attempts = row_count;

  -- 2. Paid Summit registrations that are NOT real customers (test tickets).
  delete from public.summit_registrations
  where payment_status = 'paid' and lower(email) <> all(keep_emails);
  get diagnostics n_paid_regs = row_count;

  -- 3. Unpaid TEST registrations only.
  delete from public.summit_registrations
  where payment_status <> 'paid'
    and lower(email) <> all(keep_emails)
    and ( lower(email) = any(test_emails) or email ilike any(test_patterns) );
  get diagnostics n_unpaid_regs = row_count;

  -- 4. Nothing may show "confirmed" without a payment.
  update public.summit_registrations
     set status = 'pending', confirmed_at = null
   where payment_status <> 'paid' and status = 'confirmed';
  get diagnostics n_reset = row_count;

  -- 5. Subscription payment rows (all test while in Free mode).
  if delete_all_subscription_payments then
    delete from public.payments;
    get diagnostics n_payments = row_count;
  end if;

  -- 6. Payment alert noise generated by test checkouts.
  delete from public.notifications
  where type in ('payment_alert', 'abandoned_checkout')
     or title = 'Reached checkout — payment pending';
  get diagnostics n_notifs = row_count;

  raise notice 'DONE. paid test registrations deleted: %, unpaid test registrations deleted: %, checkout attempts deleted: %, subscription payment rows deleted: %, alert notifications deleted: %, wrongly-"confirmed" reset: %',
    n_paid_regs, n_unpaid_regs, n_attempts, n_payments, n_notifs, n_reset;
end $$;


-- ── STEP 3: verify. The paid count and revenue should now match Paystack. ───
select count(*) as paid_registrations, coalesce(sum(amount_paid), 0) as revenue_ngn
from public.summit_registrations where payment_status = 'paid';
